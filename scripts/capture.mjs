import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';
console.log('Launching browser');
const browser = await chromium.launch({ channel: 'msedge', headless: true, timeout: 120000 });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1 });
page.on('pageerror', error => console.log('PAGE ERROR', error.message));
page.on('console', msg => { if (msg.type() === 'error') console.log('CONSOLE ERROR', msg.text().slice(0,500)); });
console.log('Loading film');
await page.goto('http://127.0.0.1:5197', { waitUntil: 'domcontentloaded', timeout: 120000 });
await page.locator('#film-name').waitFor({ timeout: 120000 });
await page.evaluate(() => document.fonts.ready);
await page.waitForTimeout(2200);
mkdirSync('artifacts', { recursive: true });
await page.screenshot({ path: 'artifacts/hero-desktop.png' });
console.log(await page.locator('#film-name').textContent());
console.log('Canvas', await page.locator('#world').evaluate(el=>({width:el.width,height:el.height})), 'fallback', await page.locator('#render-status').isVisible());
await page.locator('#start').click();
await page.waitForTimeout(2200);
await page.locator('#play').click();
await page.screenshot({ path: 'artifacts/film-desktop.png' });
await browser.close();
